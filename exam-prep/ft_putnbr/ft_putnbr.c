#include <unistd.h>

void	ft_putnbr(int nb)
{
	char c;
	long int n;

	n = nb;

	if(n < 0){
	write(1, "-", 1);
	n = n * -1;
	}

	if(n < 10)
	{
	c = n + '0';
	}

	if(n > 9)
	{
	c = n % 10 + '0';
	ft_putnbr(n / 10);
	}
	
	write(1, &c, 1);
	
}


