#include <unistd.h>

void	ft_print_comb2(void)
{
	int	n1;
	int	n2;

	n1 = 0;
	while (n1 < 100)
	{
		n2 = n1 + 1;
		while (n2 < 100)
		{
			write(1, &"0123456789"[n1 / 10], 1);
			write(1, &"0123456789"[n1 % 10], 1);
			write(1, " ", 1);
			write(1, &"0123456789"[n2 / 10], 1);
			write(1, &"0123456789"[n2 % 10], 1);
			if (n1 != 98 || n2 != 99)
				write(1, ", ", 2);
			n2++;
		}
		n1++;
	}
}

